#!/usr/bin/env node
// Deterministic half of the wiki skill. Usage: wiki.mjs <lint|index> <vault> [--json]
// Config: <vault>/.wiki.json {"raw": "<folder>", "wiki": "<folder>"}, paths relative to the vault.
// Output shape: references/schemas/wiki.schema.md. `lint` exits 1 when it finds a broken link.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, relative, resolve } from 'node:path';

const INDEX = 'index.md';
const norm = (s) => s.normalize('NFC').toLowerCase();

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || e.name === 'node_modules') continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

// [[Target#Heading|alias]] and [[folder/Target]] both resolve to the target's name.
export function links(text) {
  return [...text.matchAll(/\[\[([^\]|#^]+)[^\]]*\]\]/g)].map((m) => m[1].trim());
}

export function loadConfig(vault) {
  const file = join(vault, '.wiki.json');
  if (!existsSync(file)) throw new Error(`no ${file}: write {"raw": "...", "wiki": "..."} first`);
  const { raw, wiki } = JSON.parse(readFileSync(file, 'utf8'));
  if (!raw || !wiki) throw new Error('.wiki.json needs "raw" and "wiki"');
  return { raw, wiki };
}

function frontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(text);
  const block = m ? m[1] : '';
  const get = (k) => new RegExp(`^${k}:\\s*(.*)$`, 'm').exec(block)?.[1].replace(/^(["'])(.*)\1$/, '$2').trim() ?? '';
  return { type: get('type'), summary: get('summary'), sources: links(block.split('\n').filter((l) => /^sources:/.test(l) || /^\s+-/.test(l)).join('\n')), body: m ? text.slice(m[0].length) : text };
}

export function scan(vaultArg) {
  const vault = resolve(vaultArg);
  const cfg = loadConfig(vault);
  const wikiDir = resolve(vault, cfg.wiki);
  const rawDir = resolve(vault, cfg.raw);
  const files = walk(vault);
  const byName = new Map();
  for (const f of files) {
    const key = norm(basename(f).replace(/\.md$/, ''));
    byName.set(key, [...(byName.get(key) ?? []), f]);
  }
  const resolveLink = (t) => byName.get(norm(basename(t).replace(/\.md$/, '')));
  const pages = files
    .filter((f) => f.endsWith('.md') && f.startsWith(wikiDir + '/') && basename(f) !== INDEX)
    .map((f) => {
      const text = readFileSync(f, 'utf8');
      return { file: f, rel: relative(vault, f), name: basename(f, '.md'), mtime: statSync(f).mtimeMs, text, ...frontmatter(text) };
    });
  return { vault, cfg, wikiDir, rawDir, files, byName, resolveLink, pages };
}

export function lint(vaultArg) {
  const { vault, rawDir, files, resolveLink, pages } = scan(vaultArg);
  const rel = (f) => relative(vault, f);
  const inbound = new Map(pages.map((p) => [norm(p.name), new Set()]));
  const broken = [];
  const oneWay = [];
  const stale = [];
  const cited = new Set();
  for (const p of pages) {
    for (const t of new Set(links(p.text))) {
      const hit = resolveLink(t);
      if (!hit) { broken.push({ page: p.rel, link: t }); continue; }
      hit.forEach((h) => cited.add(h));
      if (inbound.has(norm(basename(t))) && norm(basename(t)) !== norm(p.name)) inbound.get(norm(basename(t))).add(norm(p.name));
    }
    for (const s of p.sources) {
      const src = resolveLink(s)?.[0];
      if (src && statSync(src).mtimeMs > p.mtime) stale.push({ page: p.rel, source: rel(src) });
    }
  }
  for (const p of pages) {
    for (const t of new Set(links(p.text))) {
      const other = pages.find((q) => norm(q.name) === norm(basename(t)));
      if (other && other !== p && !links(other.text).some((x) => norm(basename(x)) === norm(p.name))) oneWay.push({ from: p.rel, to: other.rel });
    }
  }
  const orphans = pages.filter((p) => inbound.get(norm(p.name)).size === 0).map((p) => p.rel);
  const unsummarized = files.filter((f) => f.endsWith('.md') && f.startsWith(rawDir + '/') && !cited.has(f)).map(rel);
  // A name used as a link target in 3+ pages with no page of its own is a concept page waiting to be written.
  const counts = new Map();
  for (const p of pages) for (const t of new Set(links(p.text))) if (!resolveLink(t)) counts.set(t, (counts.get(t) ?? 0) + 1);
  const candidates = [...counts].filter(([, n]) => n >= 2).map(([name, n]) => ({ name, pages: n }));
  return { pages: pages.length, broken, orphans, oneWay, stale, unsummarized, candidates };
}

export function buildIndex(vaultArg) {
  const { wikiDir, pages } = scan(vaultArg);
  const groups = {};
  for (const p of pages) (groups[p.type || 'other'] ??= []).push(p);
  const out = ['---', 'type: index', '---', '', '# Index', '', 'Generated by `wiki.mjs index`. Do not edit by hand.', ''];
  for (const type of Object.keys(groups).sort()) {
    out.push(`## ${type}`, '');
    for (const p of groups[type].sort((a, b) => a.name.localeCompare(b.name))) out.push(`- [[${p.name}]]${p.summary ? `: ${p.summary}` : ''}`);
    out.push('');
  }
  const file = join(wikiDir, INDEX);
  writeFileSync(file, out.join('\n'));
  return { index: file, pages: pages.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [cmd, vault] = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const json = process.argv.includes('--json');
  if (!['lint', 'index'].includes(cmd) || !vault || !existsSync(vault)) {
    console.error('usage: wiki.mjs <lint|index> <vault> [--json]');
    process.exit(2);
  }
  try {
    const result = cmd === 'lint' ? lint(vault) : buildIndex(vault);
    if (json || cmd === 'index') console.log(JSON.stringify(result, null, 2));
    else {
      console.log(`${result.pages} pages`);
      for (const [k, v] of Object.entries(result)) if (Array.isArray(v)) console.log(`${k}: ${v.length}`, ...v.map((x) => '\n  ' + (typeof x === 'string' ? x : JSON.stringify(x))));
    }
    process.exit(cmd === 'lint' && result.broken.length ? 1 : 0);
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
}
